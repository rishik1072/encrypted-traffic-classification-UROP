"""
Ground-Truth Annotation and Activity Association Engine for Dataset V3.

Associates observed physical flows with controlled application activities.
Enforces strict separation between verified application traffic and background noise.
Decouples label quality (certainty of application origin) from packet prefix eligibility.
Never uses model predictions or confidence outputs to assign ground-truth labels.
"""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Dict, List, Optional, Set

from research.dataset_v3.config import DatasetV3Config
from research.dataset_v3.schemas import (
    VALID_LABEL_QUALITIES,
    VALID_LABEL_SOURCES,
    VALID_TRAFFIC_CLASSES,
    FlowIndexRecord,
    LabelRecord,
)

logger = logging.getLogger("research.dataset_v3.annotation")


class GroundTruthAnnotator:
    """
    Manages ground-truth label assignment for flows in a Dataset V3 session.
    """

    def __init__(self, config: DatasetV3Config) -> None:
        self.config = config
        self.session_id = config.session_id
        self.intended_class = config.intended_traffic_class
        self.application_alias = config.application_alias
        self.annotator = config.collection_operator_label

    def generate_initial_labels(
        self,
        flow_records: List[FlowIndexRecord],
        verified_flow_ids: Optional[Set[str]] = None,
        ambiguous_flow_ids: Optional[Set[str]] = None,
        residual_other_flow_ids: Optional[Set[str]] = None,
        primary_flow_ids: Optional[Set[str]] = None,
        has_explicit_evidence: bool = True,
    ) -> List[LabelRecord]:
        """
        Generates initial candidate labels for flows observed during a controlled session.

        Ground-Truth Principles (Phase 2A.3):
        1. VERIFIED: traffic_class contains one of the six validated classes.
           Requires explicit flow attribution evidence or operator verification.
        2. UNLABELLED: traffic_class = None, label_quality = 'UNLABELLED'.
           Assigned to background traffic not generated by the target application.
        3. AMBIGUOUS: traffic_class = None, label_quality = 'AMBIGUOUS'.
           Assigned to flows with only temporal overlap or uncertain attribution.
        4. 'Other' is reserved EXCLUSIVELY for flows independently verified to belong
           to the residual traffic category (label_quality must be VERIFIED).
        5. Unlabelled and ambiguous flows must have traffic_class=None so they can NEVER
           silently enter supervised training or evaluation partitions.
        6. If assignment is based only on temporal overlap with the browsing window,
           it must NOT automatically receive VERIFIED status.
        """
        now_utc = datetime.now(timezone.utc).isoformat()
        labels: List[LabelRecord] = []

        # Handle backward-compatible primary_flow_ids
        v_ids: Optional[Set[str]] = set(verified_flow_ids) if verified_flow_ids is not None else None
        if primary_flow_ids is not None:
            if has_explicit_evidence:
                v_ids = (v_ids or set()) | set(primary_flow_ids)
            else:
                ambiguous_flow_ids = (ambiguous_flow_ids or set()) | set(primary_flow_ids)

        a_ids: Set[str] = set(ambiguous_flow_ids) if ambiguous_flow_ids is not None else set()
        r_ids: Set[str] = set(residual_other_flow_ids) if residual_other_flow_ids is not None else set()

        for flow in flow_records:
            cnt = flow.packet_count
            p3 = flow.prefix_3_available
            p5 = flow.prefix_5_available
            p10 = flow.prefix_10_available
            p20 = flow.prefix_20_available

            # 1. Explicitly Verified Target Flow
            if v_ids is not None and flow.flow_id in v_ids:
                lbl = LabelRecord(
                    session_id=self.session_id,
                    flow_id=flow.flow_id,
                    traffic_class=self.intended_class,
                    application_alias=self.application_alias,
                    label_source="OPERATOR_CONTROLLED",
                    label_quality="VERIFIED",
                    annotator=self.annotator,
                    annotation_timestamp=now_utc,
                    packet_count=cnt,
                    prefix_3_available=p3,
                    prefix_5_available=p5,
                    prefix_10_available=p10,
                    prefix_20_available=p20,
                )
            # 2. Independently Verified Residual Other Flow
            elif flow.flow_id in r_ids:
                lbl = LabelRecord(
                    session_id=self.session_id,
                    flow_id=flow.flow_id,
                    traffic_class="Other",
                    application_alias="residual_other",
                    label_source="INDEPENDENT_VERIFICATION",
                    label_quality="VERIFIED",
                    annotator=self.annotator,
                    annotation_timestamp=now_utc,
                    packet_count=cnt,
                    prefix_3_available=p3,
                    prefix_5_available=p5,
                    prefix_10_available=p10,
                    prefix_20_available=p20,
                )
            # 3. Ambiguous / Temporal Overlap Only Flow
            elif flow.flow_id in a_ids or (v_ids is None and not a_ids and not r_ids):
                # When no explicit attribution is supplied, all flows have only temporal overlap
                lbl = LabelRecord(
                    session_id=self.session_id,
                    flow_id=flow.flow_id,
                    traffic_class=None,
                    application_alias=None,
                    label_source="TEMPORAL_HEURISTIC",
                    label_quality="AMBIGUOUS",
                    annotator=self.annotator,
                    annotation_timestamp=now_utc,
                    packet_count=cnt,
                    prefix_3_available=p3,
                    prefix_5_available=p5,
                    prefix_10_available=p10,
                    prefix_20_available=p20,
                )
            # 4. Background Unlabelled Traffic
            else:
                lbl = LabelRecord(
                    session_id=self.session_id,
                    flow_id=flow.flow_id,
                    traffic_class=None,
                    application_alias="background_unattributed",
                    label_source="BACKGROUND_UNLABELLED",
                    label_quality="UNLABELLED",
                    annotator=self.annotator,
                    annotation_timestamp=now_utc,
                    packet_count=cnt,
                    prefix_3_available=p3,
                    prefix_5_available=p5,
                    prefix_10_available=p10,
                    prefix_20_available=p20,
                )

            labels.append(lbl)

        logger.info(
            "Generated %d ground-truth label records (%d VERIFIED, %d AMBIGUOUS, %d UNLABELLED, %d prefix_3 eligible)",
            len(labels),
            sum(1 for r in labels if r.label_quality == "VERIFIED"),
            sum(1 for r in labels if r.label_quality == "AMBIGUOUS"),
            sum(1 for r in labels if r.label_quality == "UNLABELLED"),
            sum(1 for r in labels if r.prefix_3_available),
        )
        return labels

    def apply_manual_override(
        self,
        current_labels: List[LabelRecord],
        flow_id: str,
        traffic_class: Optional[str],
        label_quality: str,
        label_source: str = "MANUAL_AUDIT",
        notes: str = "",
    ) -> List[LabelRecord]:
        """Applies a verified manual operator override for a specific flow."""
        if label_quality not in VALID_LABEL_QUALITIES:
            raise ValueError(f"Invalid label quality: {label_quality}")

        if label_quality == "VERIFIED":
            if traffic_class is None:
                raise ValueError("VERIFIED label must specify a valid traffic_class, not None.")
            if traffic_class not in VALID_TRAFFIC_CLASSES:
                raise ValueError(f"Invalid traffic class: {traffic_class}")
        elif label_quality in ("UNLABELLED", "AMBIGUOUS"):
            traffic_class = None

        if traffic_class == "Other" and label_quality != "VERIFIED":
            raise ValueError("'Other' is reserved exclusively for VERIFIED residual flows.")

        now_utc = datetime.now(timezone.utc).isoformat()
        updated_labels: List[LabelRecord] = []

        for r in current_labels:
            if r.flow_id == flow_id:
                app_alias = r.application_alias if label_quality == "VERIFIED" else None
                updated_record = LabelRecord(
                    session_id=r.session_id,
                    flow_id=r.flow_id,
                    traffic_class=traffic_class,
                    application_alias=app_alias,
                    label_source=label_source,
                    label_quality=label_quality,
                    annotator=self.annotator,
                    annotation_timestamp=now_utc,
                    packet_count=r.packet_count,
                    prefix_3_available=r.prefix_3_available,
                    prefix_5_available=r.prefix_5_available,
                    prefix_10_available=r.prefix_10_available,
                    prefix_20_available=r.prefix_20_available,
                )
                updated_labels.append(updated_record)
            else:
                updated_labels.append(r)

        return updated_labels
